    public String getContato() {
        return contato;
    }

    public void setContato(String contato) {
        this.contato = contato;
    }

    public String getEnd_comp() {
        return end_comp;
    }

    public void setEnd_comp(String end_comp) {
        this.end_comp = end_comp;
    }
